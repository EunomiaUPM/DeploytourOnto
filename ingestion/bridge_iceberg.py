import os
import shutil
import glob
import pyarrow.parquet as pq
from pyiceberg.catalog.sql import SqlCatalog
from pyiceberg.schema import Schema
from pyiceberg.types import (
    StringType,
    IntegerType,
    FloatType,
    NestedField,
)

def main():
    raw_dir = "/tmp/raw_parquet"
    fiware_parquet = os.path.join(raw_dir, "fiware_accommodations.parquet")
    segittur_parquet = os.path.join(raw_dir, "segittur_destinos.parquet")

    if not os.path.exists(fiware_parquet) or not os.path.exists(segittur_parquet):
        raise FileNotFoundError(f"Parquet files not found in {raw_dir}")

    # Read the parquet tables generated by Go parquet-go
    fiware_table = pq.read_table(fiware_parquet)
    segittur_table = pq.read_table(segittur_parquet)

    print(f"[bridge-iceberg] Loaded FIWARE parquet with {fiware_table.num_rows} rows")
    print(f"[bridge-iceberg] Loaded SEGITTUR parquet with {segittur_table.num_rows} rows")

    os.makedirs("/data", exist_ok=True)
    sqlite_db = "/tmp/iceberg_catalog.db"
    if os.path.exists(sqlite_db):
        os.remove(sqlite_db)

    # 1. Initialize FIWARE Iceberg Table
    loc_a = "/data/lakehouse_a_fiware"
    if os.path.exists(loc_a):
        shutil.rmtree(loc_a)
    os.makedirs(loc_a, exist_ok=True)

    cat_a = SqlCatalog("fiware_cat", uri=f"sqlite:///{sqlite_db}", warehouse="file:///data")
    try:
        cat_a.create_namespace("fiware")
    except Exception:
        pass
    try:
        cat_a.drop_table("fiware.accommodations")
    except Exception:
        pass

    schema_a = Schema(
        NestedField(field_id=1, name="id", field_type=StringType(), required=False),
        NestedField(field_id=2, name="name", field_type=StringType(), required=False),
        NestedField(field_id=3, name="category", field_type=StringType(), required=False),
        NestedField(field_id=4, name="capacity_beds", field_type=IntegerType(), required=False),
        NestedField(field_id=5, name="occupancy_rate", field_type=FloatType(), required=False),
        NestedField(field_id=6, name="latitude", field_type=FloatType(), required=False),
        NestedField(field_id=7, name="longitude", field_type=FloatType(), required=False),
        NestedField(field_id=8, name="municipality_code", field_type=StringType(), required=False),
    )
    tbl_a = cat_a.create_table(
        "fiware.accommodations",
        schema=schema_a,
        location=f"file://{loc_a}"
    )
    tbl_a.append(fiware_table)

    # Link/Copy latest metadata to v1.metadata.json
    meta_dir_a = os.path.join(loc_a, "metadata")
    meta_files_a = sorted(glob.glob(os.path.join(meta_dir_a, "*.metadata.json")))
    if not meta_files_a:
        raise RuntimeError("No metadata.json produced for FIWARE lakehouse")
    latest_meta_a = meta_files_a[-1]
    v1_meta_a = os.path.join(meta_dir_a, "v1.metadata.json")
    shutil.copyfile(latest_meta_a, v1_meta_a)
    print(f"[bridge-iceberg] Created {v1_meta_a} (source: {os.path.basename(latest_meta_a)})")

    # 2. Initialize SEGITTUR Iceberg Table
    loc_b = "/data/lakehouse_b_segittur"
    if os.path.exists(loc_b):
        shutil.rmtree(loc_b)
    os.makedirs(loc_b, exist_ok=True)

    cat_b = SqlCatalog("segittur_cat", uri=f"sqlite:///{sqlite_db}", warehouse="file:///data")
    try:
        cat_b.create_namespace("segittur")
    except Exception:
        pass
    try:
        cat_b.drop_table("segittur.destinos")
    except Exception:
        pass

    schema_b = Schema(
        NestedField(field_id=1, name="id_destino", field_type=StringType(), required=False),
        NestedField(field_id=2, name="denominacion_recurso", field_type=StringType(), required=False),
        NestedField(field_id=3, name="tipo_espacio", field_type=StringType(), required=False),
        NestedField(field_id=4, name="visitantes_mensuales", field_type=IntegerType(), required=False),
        NestedField(field_id=5, name="gasto_medio_diario_eur", field_type=FloatType(), required=False),
        NestedField(field_id=6, name="latitud", field_type=FloatType(), required=False),
        NestedField(field_id=7, name="longitud", field_type=FloatType(), required=False),
        NestedField(field_id=8, name="codigo_ine_municipio", field_type=StringType(), required=False),
    )
    tbl_b = cat_b.create_table(
        "segittur.destinos",
        schema=schema_b,
        location=f"file://{loc_b}"
    )
    tbl_b.append(segittur_table)

    meta_dir_b = os.path.join(loc_b, "metadata")
    meta_files_b = sorted(glob.glob(os.path.join(meta_dir_b, "*.metadata.json")))
    if not meta_files_b:
        raise RuntimeError("No metadata.json produced for SEGITTUR lakehouse")
    latest_meta_b = meta_files_b[-1]
    v1_meta_b = os.path.join(meta_dir_b, "v1.metadata.json")
    shutil.copyfile(latest_meta_b, v1_meta_b)
    print(f"[bridge-iceberg] Created {v1_meta_b} (source: {os.path.basename(latest_meta_b)})")

    print("[bridge-iceberg] Iceberg lakehouse generation completed successfully!")

if __name__ == "__main__":
    main()
